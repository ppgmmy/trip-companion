function normalize(str) {
  return (str || "").trim().toLowerCase();
}

export function guideForTrip(trip) {
  if (!trip) return { label: "好去處", places: GENERIC_GUIDE, source: "generic" };
  const city = normalize(trip.city);
  const country = normalize(trip.country);
  for (const guide of CITY_GUIDES) {
    if (guide.keys.some((k) => city.includes(k) || country.includes(k))) {
      return { label: guide.label, places: guide.places, source: "city" };
    }
  }
  const byCurrency = CURRENCY_GUIDES[trip.targetCurrency];
  if (byCurrency) {
    return { label: `${trip.country || trip.city} 周邊推介`, places: byCurrency, source: "country" };
  }
  return { label: "通用好去處", places: GENERIC_GUIDE, source: "generic" };
}
